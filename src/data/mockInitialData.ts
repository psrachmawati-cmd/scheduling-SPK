/**
 * STANDARD WBS GENERATION FOR ALL 26 SPKs
 * Structured strictly according to the official SOW Specification (53 tasks + 5 milestones M1-M5)
 */
const ALL_SPK_WBS_NODES: WbsNode[] = INITIAL_PROJECTS.flatMap((proj) => {
  const rawNodes = generateStandardWbsForProject(proj.id, proj.startDate, proj.finishDate, {
    subcontractorName: proj.subcontractor,
    defaultPic: proj.picName,
  });

  const targetActual = proj.currentProgressActual;
  const targetPlan = proj.targetProgressPlan;

  const adjusted = rawNodes.map((node) => {
    const isLeaf = !rawNodes.some((n) => n.parentId === node.id);
    if (!isLeaf || node.isMilestone) return node;

    // Relative timeline position
    const startMs = new Date(proj.startDate).getTime();
    const finishMs = new Date(proj.finishDate).getTime();
    const taskFinishMs = new Date(node.finishPlan).getTime();
    const ratio = Math.max(0, Math.min(1, (taskFinishMs - startMs) / Math.max(1, finishMs - startMs)));

    let actual = 0;
    if (ratio <= targetActual / 100) {
      actual = 100;
    } else if (ratio <= targetActual / 100 + 0.15) {
      actual = Math.round(Math.max(0, 1 - (ratio - targetActual / 100) / 0.15) * 80);
    }

    let plan = 0;
    if (ratio <= targetPlan / 100) {
      plan = 100;
    } else if (ratio <= targetPlan / 100 + 0.15) {
      plan = Math.round(Math.max(0, 1 - (ratio - targetPlan / 100) / 0.15) * 80);
    }

    let status: TaskStatus = 'NOT_STARTED';
    if (actual >= 100) status = 'COMPLETED';
    else if (actual > 0) status = actual < plan - 15 ? 'DELAYED' : 'ON_PROGRESS';

    return {
      ...node,
      progressPlan: plan,
      progressActual: actual,
      status,
      baselineLocked: true,
      baselineProgressPlan: plan,
      subcontractorName: proj.subcontractor,
      subcontractorId: proj.subcontractor?.includes('SYAHRIAL') ? 'sub-02' : 'sub-01',
    };
  });

  return calculateRollup(adjusted);
});

